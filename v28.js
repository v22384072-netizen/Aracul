// V28 — единая история расклада: связи между картами
(function(){
  function group(n){return n<=20?"resource":n<=40?"shadow":"action"}
  function transition(a,b){
    const g1=group(a.n),g2=group(b.n);
    const map={
      "resource-shadow":"Ресурс упирается в препятствие: важно увидеть, где доступная опора сталкивается со старым ограничением.",
      "shadow-action":"Препятствие уже показывает точку действия: дальше полезно не анализировать бесконечно, а менять одно звено.",
      "action-resource":"Действие приводит обратно к опоре: результат стоит закрепить в системе, а не оставить единичным усилием.",
      "resource-action":"То, что уже есть, можно перевести в действие без ожидания идеальных условий.",
      "action-shadow":"Действие вскрывает скрытую помеху: обратная связь здесь важнее первоначального плана.",
      "shadow-resource":"После признания ограничения становится виден ресурс, который раньше был перекрыт.",
      "resource-resource":"Две опоры усиливают друг друга: ищи между ними общий принцип.",
      "shadow-shadow":"Две тени указывают на повторяемый механизм, а не на случайную помеху.",
      "action-action":"Два действия образуют процесс: важен порядок шагов и наблюдаемый результат."
    };
    return map[g1+"-"+g2];
  }
  window.synthesis=function(cards,q,total,intent){
    const xs=cards||[];
    if(!xs.length)return "В раскладе пока нет карт.";
    const names=xs.map(x=>"«"+x.c.title+"»");
    const lead=total===3
      ?"Первая карта показывает исходную точку, вторая — механизм за ней, третья — направление изменения."
      :"Пять карт складываются в последовательность: текущее состояние → основание → препятствие → ресурс → следующий шаг.";
    const links=[];
    for(let i=0;i<xs.length-1;i++)links.push(transition(xs[i],xs[i+1]));
    const first=xs[0],last=xs[xs.length-1];
    const intentText={
      decision:"Для решения проверь, выдерживает ли выбранный путь реальную цену и условия.",
      why:"Для вопроса «почему» ищи повторяющееся звено, которое соединяет начало и конец ситуации.",
      action:"Для действия важен не масштаб шага, а факт, который появится после него.",
      outcome:"Для результата смотри на условия и зависимости, а не на обещание неизбежного исхода.",
      timing:"Для срока отслеживай контрольную точку, которая показывает готовность следующего этапа.",
      future:"Для будущего читай линию как сценарий при сохранении нынешней динамики, а не как неизбежность.",
      choice:"Для выбора используй линию как критерий сравнения вариантов, а не как замену собственного решения.",
      insight:"Для наблюдения ищи один механизм, который становится яснее от карты к карте."
    }[intent]||"Используй линию как способ точнее увидеть ситуацию.";
    const mechanism=xs.map(x=>x.row&&x.row[0]).filter(Boolean);
    const unique=[...new Set(mechanism)];
    const action=last.row&&last.row[3]?last.row[3]:"Переведи последнее наблюдение в один проверяемый шаг.";
    return lead+" Вопрос: «"+String(q||"").slice(0,180)+"». Линия начинается с "+names[0]+" и заканчивается "+names[names.length-1]+". "+links.join(" ")+" "+intentText+" "+(unique.length>1?"Общий механизм расклада проходит через: "+unique.join(", ")+". ":"")+"Финальная точка — не предсказание, а проверка: "+action+" "+(total===3?"Спроси себя: что изменится, если сделать этот шаг?":"После шага вернись к первой карте и проверь, что действительно изменилось в исходной ситуации.");
  };
  document.addEventListener("click",function(e){
    const b=e.target.closest("#v27RevealLine");if(!b)return;
    const box=b.closest(".v27-finale");if(box)box.querySelector("p")?.classList.add("v28-line");
  });
})();