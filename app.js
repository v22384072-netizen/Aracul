function readingFor(c,q=''){
  const ctx=contextOf(q);
  if(ctx==='money') return {meaning:c.meaning,shadow:c.shadow,direction:c.direction,question:c.question};
  return {
    meaning:universalReadings[c.id]||c.meaning,
    shadow:universalShadows[c.id]||'Обрати внимание на то, что мешает тебе видеть ситуацию ясно.',
    direction:universalDirections[c.id]||'Сделай один спокойный и конкретный следующий шаг.',
    question:universalQuestions[c.id]||'Что эта ситуация хочет показать тебе прямо сейчас?'
  };
}


function showReading(c,q){
  const r=readingFor(c,q);
  $('#reading').classList.add('visible');
  $('#readingQuestion').textContent=q?'Ты спросил: «'+q+'»':'Твой вопрос был услышан картами.';
  $('#readingLead').textContent=personalLead(c,q);
  $('#readingShadow').textContent=r.shadow;
  $('#readingDirection').textContent=r.direction;
  $('#readingNext').textContent=r.question;
  $('#another').textContent='Задать новый вопрос';
  setTimeout(()=>$('#reading').scrollIntoView({behavior:'smooth',block:'start'}),220);
}

function interpretSpread(){
  const result=$('#spreadReading');
  const positions=spreadSize===1?['СУТЬ ВОПРОСА']:spreadSize===3?['ЧТО ПРОИСХОДИТ','ЧТО ОСТАЁТСЯ В ТЕНИ','СЛЕДУЮЩИЙ ШАГ']:['СУТЬ','ПРИЧИНА','ТЕНЬ','РЕСУРС','СЛЕДУЮЩИЙ ШАГ'];
  result.innerHTML='<div class="reading-block"><small>ВОПРОС, С КОТОРЫМ ТЫ ПРИШЁЛ</small><p>«'+esc(currentQuestion)+'»</p></div>'+spreadCards.map((c,i)=>{
    const r=readingFor(c,currentQuestion);
    return '<article><small>'+String(i+1).padStart(2,'0')+' · '+positions[i]+'</small><h3>'+esc(c.title)+'</h3><p>'+personalLead(c,currentQuestion)+'</p><div class="reading-sub"><b>ТЕНЬ</b><span>'+esc(r.shadow)+'</span></div><div class="reading-sub"><b>НАПРАВЛЕНИЕ</b><span>'+esc(r.direction)+'</span></div><div class="reading-sub"><b>ВОПРОС К ТЕБЕ</b><span>'+esc(r.question)+'</span></div></article>';
  }).join('')+'<button class="gold wide" onclick="screen(\'home\')">Задать новый вопрос</button>';
  result.classList.add('visible');
  result.scrollIntoView({behavior:'smooth',block:'start'});
  haptic('success');
}


/* Финальная полировка диалога.
   В режиме вопроса показываем только трактовку, относящуюся к выбранному контексту.
   Не повторяем служебные фразы и не выводим ключевые слова вопроса как "анализ". */
function personalLead(c,q=''){
  const ctx=contextOf(q);
  if(ctx==='money') return c.meaning;
  const text=universalReadings[c.id]||c.meaning;
  const intro={
    relations:'В твоём вопросе об отношениях эта карта говорит о',
    work:'В вопросе о деятельности эта карта говорит о',
    day:'Для твоего дня эта карта говорит о',
    decision:'Если смотреть на твой выбор, карта говорит о',
    inner:'Если смотреть на твоё состояние, карта говорит о',
    people:'В вопросе о людях карта говорит о',
    general:'В твоём вопросе карта говорит о'
  }[ctx]||'В твоём вопросе карта говорит о';
  return intro+' '+text.charAt(0).toLowerCase()+text.slice(1);
}

