/* V20 — semantic personalization layer */
(function(){
  function v20Profile(q){
    const s=(q||"").toLowerCase();
    const direct=/(стоит ли|нужно ли|можно ли|получится ли|будет ли|смогу ли|удастся ли|когда|почему|что делать|как мне|что выбрать|какой вариант|между)/.test(s);
    const urgency=/(срочно|сейчас|сегодня|немедленно|пора|долго|затянул|не успеваю)/.test(s);
    const constraint=/(денег нет|не хватает|долг|кредит|ипотек|боюсь|страшно|не уверен|сомневаюсь|не могу|не получается)/.test(s);
    const agency=/(я хочу|хочу|мне нужно|мне важно|решил|решила|думаю|планирую|собираюсь)/.test(s);
    return {direct,urgency,constraint,agency};
  }
  function v20Answer(n,q,c){
    const p=questionProfile(q), intent=deepIntent(q), v=v20Profile(q);
    const row=CARD_MECHANISM[n], h=answerHash(String(n)+"|V20|"+q);
    if(!row)return v17PersonalizedAnswer(n,q,c);
    const key=deepTopicKey(p);
    const topic=(INTENT_TOPIC[key]&&INTENT_TOPIC[key][intent])||"Сверь чтение с конкретными условиями ситуации.";
    const voices=(typeof CARD_VOICE!=="undefined"&&CARD_VOICE[n-1])||"смотрит на механизм ситуации";
    const openings={
      decision:["Сначала не выбирай. Определи, какое условие должно выдержать выбранный вариант.","Здесь полезнее не искать знак, а проверить цену решения.","Перед решением карта возвращает тебя к критерию, который нельзя обойти."],
      why:["Здесь важнее не виновник, а механизм, который продолжает повторяться.","Причина становится видимой там, где ситуация воспроизводится снова.","Посмотри не на последнее событие, а на правило, которое его поддерживает."],
      action:["Карта просит превратить вопрос в маленький эксперимент.","Не меняй всю ситуацию сразу. Возьми один рычаг.","Здесь полезность карты начинается там, где появляется конкретное действие."],
      outcome:["Карта не обещает исход — она показывает условие исхода.","Вместо гарантии здесь есть зависимость, которую можно проверить.","Результат пока открыт; важнее увидеть, что на него реально влияет."],
      timing:["Срок начинается не с даты, а с готовности условий.","Вместо угадывания даты найди контрольную точку.","Здесь время связано с последовательностью событий, а не с предсказанием."],
      future:["Это не фиксированное будущее, а продолжение нынешней динамики.","Сценарий меняется вместе с действиями, которые ты делаешь сейчас.","Карта показывает траекторию, которую можно корректировать."],
      choice:["Не отдавай выбор карте — используй её как критерий сравнения.","Здесь важнее различие между вариантами, которое переживёт первый импульс.","Сравни варианты через цену, ресурс и последствия."],
      insight:["Образ нужен здесь как новая оптика на уже существующую ситуацию.","Не ищи буквальное предсказание. Ищи механизм.","Карта делает заметным то, что легко пропустить внутри вопроса."]
    };
    const lead=(openings[intent]||openings.insight)[h%3];
    let focus;
    if(v.constraint)focus="В вопросе есть ограничение или напряжение, поэтому сначала проверь управляемую часть ситуации: "+row[2]+".";
    else if(v.urgency)focus="Поскольку для тебя важен темп, отдели срочность от действительно важного условия: "+row[2]+".";
    else if(v.agency)focus="Ты уже обозначил своё намерение; карта помогает уточнить способ действия: "+row[3]+".";
    else focus="Точка проверки здесь: "+row[2]+".";
    const architecture=intent==="decision"?"критерий → цена → проверка":intent==="why"?"повторение → механизм → разрыв":intent==="action"?"рычаг → шаг → результат":intent==="outcome"?"условие → зависимость → сигнал":intent==="timing"?"готовность → этап → признак":intent==="future"?"динамика → сценарий → влияние":intent==="choice"?"критерий → сравнение → тест":"наблюдение → смысл → проверка";
    return [
      lead,
      "Твой вопрос: «"+(p.t.length>180?p.t.slice(0,180)+"…":p.t)+"».",
      "Карта «"+c.title+"» "+voices+".",
      "Логика именно этого вопроса: "+architecture+".",
      topic,
      focus,
      "В самом образе «"+c.title+"» работает механизм «"+row[0]+"»: "+row[1],
      "Тень, которую стоит не пропустить: "+shadows[n-1],
      "Направление: "+directions[n-1],
      "Проверь это в реальности: "+row[3],
      "Чтение не заменяет факты и решение; его задача — помочь заметить следующий проверяемый элемент ситуации."
    ].join(" ");
  }
  personalizedAnswer=v20Answer;
  window.v20Answer=v20Answer;
})();