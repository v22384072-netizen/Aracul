function v17Architecture(intent,n){
 const group=n<=20?"resource":n<=40?"shadow":"action";
 const map={
  decision:group==="resource"?"ресурс → условие → цена решения":group==="shadow"?"слепая зона → риск → проверка": "действие → обратная связь → корректировка",
  why:group==="resource"?"источник → повторение → поддержка":group==="shadow"?"механизм → повторение → точка разрыва":"процесс → причина сбоя → изменение",
  action:"рычаг → малый шаг → наблюдаемый результат",
  outcome:"условие → зависимость → проверяемый сигнал",
  timing:"готовность → контрольная точка → следующий этап",
  future:"нынешняя динамика → вероятный сценарий → точка влияния",
  choice:"критерий → цена вариантов → малый тест",
  insight:"наблюдение → смысл → вопрос"
 };
 return map[intent]||map.insight;
}
